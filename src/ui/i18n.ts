let current: Dict = ru;
export let lang: 'ru' | 'en' = 'ru';

export function setLang(pref: 'ru' | 'en' | 'auto'): void {
  lang = pref === 'auto' ? (navigator.language?.toLowerCase().startsWith('ru') ? 'ru' : 'en') : pref;
  current = lang === 'ru' ? ru : en;
  document.documentElement.lang = lang;
}

export function t(key: string, vars?: Record<string, string | number>): string {
  let s = current[key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** Test helper: every key must exist in both languages. */
export function missingKeys(): string[] {
  const a = Object.keys(ru);
  const b = Object.keys(en);
  return [...a.filter((k) => !(k in en)), ...b.filter((k) => !(k in ru))];
}
